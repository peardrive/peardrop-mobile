#!/usr/bin/env node
// Take a copy of a Pearkit piece into this app, or prove the copy is untouched and current.
//
//   node scripts/pearkit-sync.mjs            copy the pieces listed below from Pearkit
//   node scripts/pearkit-sync.mjs --check    exit 1 if the copy was edited by hand or is incomplete,
//                                            exit 3 if Pearkit has changed since the copy was taken
//   --from <folder>                          the Pearkit checkout to use (or PEARKIT_DIR)
//
// Pearkit (github.com/peardrive/pearkit) is the one library for pieces every app shares. Until
// it is published as a package, an app keeps a copy under src/vendor/pearkit/. The copy is made
// by this script and never edited: change the piece in Pearkit, then run this again.

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const VENDOR = path.join(APP, "src", "vendor", "pearkit");

/** The pieces this app takes. `skip` are files that only make sense inside Pearkit. */
const PIECES = [
  {
    name: "MediaPlayer",
    from: "src/components/MediaPlayer",
    // Stories are for Storybook, `web/` is the browser engine, `index.ts` exports both.
    skip: (file) => file.endsWith(".stories.tsx") || file === "index.ts" || file.startsWith("web/"),
  },
  {
    name: "FileViews",
    from: "src/components/FileViews",
    // The list, expanded and grid views of a set of files, their switcher and the download pie.
    skip: (file) => file.endsWith(".stories.tsx") || file === "index.ts",
  },
  {
    name: "ShareState",
    from: "src/components/ShareState",
    // The universal states of a share: their words, colours and progress bar. FileViews reads it.
    skip: (file) => file.endsWith(".stories.tsx") || file === "index.ts",
  },
];

const HEADER = [
  "// COPIED FROM PEARKIT by scripts/pearkit-sync.mjs. Do not edit this file here.",
  "// Change it in Pearkit, look at it in Storybook, then run `npm run pearkit:sync`.",
  "",
].join("\n");

const args = process.argv.slice(2);
const checking = args.includes("--check");
const fromArg = args.includes("--from") ? args[args.indexOf("--from") + 1] : undefined;

function sha(text) {
  return createHash("sha256").update(text).digest("hex");
}

function findPearkit() {
  const tries = [
    fromArg,
    process.env.PEARKIT_DIR,
    path.join(APP, "..", "pearkit--media-player"),
    path.join(APP, "..", "pearkit"),
  ].filter(Boolean);
  for (const dir of tries) {
    const full = path.resolve(dir);
    if (PIECES.every((p) => fs.existsSync(path.join(full, p.from)))) return full;
  }
  return null;
}

function git(dir, ...cmd) {
  try {
    return execFileSync("git", ["-C", dir, ...cmd], { encoding: "utf8" }).trim();
  } catch {
    return "";
  }
}

function listFiles(dir, base = "") {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...listFiles(path.join(dir, entry.name), rel));
    else out.push(rel);
  }
  return out.sort();
}

/** What this app keeps of one source file. */
function copyOf(file, text) {
  if (file.endsWith(".test.ts")) {
    // Pearkit runs the rule tests with vitest; this app runs the same file with jest.
    text = text.replace(/from ['"]vitest['"]/, 'from "@jest/globals"');
  }
  return /\.tsx?$/.test(file) ? HEADER + text : text;
}

function sourceFiles(pearkit, piece) {
  const dir = path.join(pearkit, piece.from);
  return listFiles(dir)
    .filter((file) => !piece.skip(file))
    .map((file) => ({ file, text: fs.readFileSync(path.join(dir, file), "utf8") }));
}

function readManifest(piece) {
  try {
    return JSON.parse(fs.readFileSync(path.join(VENDOR, piece.name, "manifest.json"), "utf8"));
  } catch {
    return null;
  }
}

function sync(pearkit) {
  for (const piece of PIECES) {
    const dest = path.join(VENDOR, piece.name);
    const files = {};
    const wanted = new Set(["manifest.json"]);
    for (const { file, text } of sourceFiles(pearkit, piece)) {
      const out = copyOf(file, text);
      const target = path.join(dest, file);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, out);
      files[file] = { copy: sha(out), source: sha(text) };
      wanted.add(file);
    }
    // A file Pearkit no longer has must not linger here.
    if (fs.existsSync(dest)) {
      for (const file of listFiles(dest)) {
        if (!wanted.has(file)) fs.unlinkSync(path.join(dest, file));
      }
    }
    const manifest = {
      piece: piece.name,
      from: `pearkit/${piece.from}`,
      branch: git(pearkit, "rev-parse", "--abbrev-ref", "HEAD"),
      commit: git(pearkit, "rev-parse", "--short", "HEAD"),
      // True when the piece was taken from work not yet committed in Pearkit.
      uncommitted: git(pearkit, "status", "--porcelain", "--", piece.from) !== "",
      files,
    };
    fs.writeFileSync(path.join(dest, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
    console.log(`${piece.name}: ${Object.keys(files).length} files copied from ${pearkit}`);
    console.log(`  (${manifest.branch} ${manifest.commit}${manifest.uncommitted ? ", with uncommitted changes" : ""})`);
  }
}

function check(pearkit) {
  let edited = 0;
  let behind = 0;
  for (const piece of PIECES) {
    const dest = path.join(VENDOR, piece.name);
    const manifest = readManifest(piece);
    if (!manifest) {
      console.log(`FAIL ${piece.name}: no copy here. Run: npm run pearkit:sync`);
      edited++;
      continue;
    }
    for (const [file, hashes] of Object.entries(manifest.files)) {
      const target = path.join(dest, file);
      if (!fs.existsSync(target)) {
        // Test files are not kept in this repo's history, so a fresh clone has none; that is
        // not a hand edit. Everything else must be there.
        if (file.endsWith(".test.ts")) continue;
        console.log(`FAIL ${piece.name}/${file}: missing. Run: npm run pearkit:sync`);
        edited++;
      } else if (sha(fs.readFileSync(target, "utf8")) !== hashes.copy) {
        console.log(`FAIL ${piece.name}/${file}: edited here. Make the change in Pearkit, then run: npm run pearkit:sync`);
        edited++;
      }
    }
    for (const file of listFiles(dest)) {
      if (file !== "manifest.json" && !manifest.files[file]) {
        console.log(`FAIL ${piece.name}/${file}: not part of the copy. Pieces are added in Pearkit.`);
        edited++;
      }
    }
    if (!pearkit) continue;
    const now = new Map(sourceFiles(pearkit, piece).map(({ file, text }) => [file, sha(text)]));
    const changed = [...now].filter(([file, hash]) => manifest.files[file]?.source !== hash).map(([file]) => file);
    const gone = Object.keys(manifest.files).filter((file) => !now.has(file));
    if (changed.length || gone.length) {
      console.log(`BEHIND ${piece.name}: Pearkit has changed (${[...changed, ...gone].join(", ")}). Run: npm run pearkit:sync`);
      behind++;
    }
  }
  if (!pearkit) console.log("NOTE no Pearkit checkout found beside this repo, so could not tell whether the copy is current.");
  if (edited) process.exit(1);
  if (behind) process.exit(3);
  console.log("OK the Pearkit copy is untouched" + (pearkit ? " and current" : ""));
}

const pearkit = findPearkit();
if (checking) {
  check(pearkit);
} else {
  if (!pearkit) {
    console.error("No Pearkit checkout found. Pass --from <folder> or set PEARKIT_DIR.");
    process.exit(2);
  }
  sync(pearkit);
}
